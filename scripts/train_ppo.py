#!/usr/bin/env python3
"""Train the graph-aware PPO policy on the fixed single-project protocol.

Data comes exclusively from ``splits.json`` (generated by ``scripts/generate_pool.py``):

  * training pool: the ``train`` split (generated PSPLIB-grid pool)
  * in-training validation: the ``validation`` split (per-size 20% cell holdout)
  * final evaluation: any of the ``evaluation`` groups (PSPLIB j30-j120 are the
    held-out benchmark with known BKS; RG300 / Patterson are generalization)

Instances are loaded through ``src.data.parsers`` + ``src.data.adapter`` so the
PPO decoder is the same serial SGS as the rule/GA/GPHH baselines.  The policy
graph is sized to a global activity/resource cap (default auto = the maximum
across every participating split), which lets one model evaluate PSPLIB
j30-j120 (32-122 activities) and RG300 (302 activities) zero-shot.

``--train-max-activities auto`` shrinks only the *training* graph to the
train+validation maximum (32 for the RG30 pool).  Every trainable policy
parameter is size-agnostic, so the policy is widened back to the global cap
before the model is saved and evaluated (``src.training.ppo.widen_policy``);
for a fixed instance the small and widened policies produce identical logits.
This cuts training time by several times without changing the learned function.

Note that the *trained* model is not bit-identical across caps even though the
function is: the action space is ``Discrete(max_activities)`` and
``torch.multinomial`` consumes RNG differently per category count, so stochastic
rollouts diverge after the first action.  Treat a different training cap as a
different random seed, and compare caps with deterministic evaluation.

Evaluation writes ``ppo_eval_summary.csv`` with columns
``suite,file,n_activities,n_resources,ppo_makespan``, consumable by
``scripts/aggregate_results.py --ppo`` for the BKS-gap comparison table.
"""
